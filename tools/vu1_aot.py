#!/usr/bin/env python3
"""vu1_aot.py CODE.bin PCHIST OUT.h - VU1 microcode -> C ahead of time, for the programs the PSP would otherwise
interpret (hle_vu1.c, built with -DVU1_AOT). CODE.bin: the VU1 code memory (16 KB, e.g. HLE_VU1_PROF's
prog_*.code dump); PCHIST: the executed addresses ("pc count" lines, gsreplay GSR_PCHIST) - only those are
translated, any other address goes back to the interpreter. Every instruction becomes vu_step() with its two words
as constants (the interpreter's own step, inlined: the decoders fold to the one instruction, the timing model, flags
and Q stay exact). A program is used only while the code memory holds it: the 64-instruction hashes at its entry
points (code_hash) are checked after every MPG upload.
The output is derived from the game's code: keep it private (it is generated on the user's machine)."""
import struct, sys
code = open(sys.argv[1], "rb").read()
pcs = sorted(int(l.split()[0], 16) for l in open(sys.argv[2]) if l.strip())
out = open(sys.argv[3], "w")
def word(pc, k): return struct.unpack_from("<I", code, pc * 8 + 4 * k)[0]
def code_hash(pc):
    h = 2166136261
    for k in range(pc, min(pc + 64, 2048)):
        h = ((h ^ word(k, 1)) * 16777619) & 0xFFFFFFFF
        h = ((h ^ word(k, 0)) * 16777619) & 0xFFFFFFFF
    return h
# programs: entries at 0 and at the second program's start (the address after the first E bit's delay slot run)
entries = [0]
for pc in range(2048):
    if (word(pc, 1) >> 30) & 1 and pc + 2 < 2048 and pc + 2 not in entries:
        entries.append(pc + 2)
        break
progs = []   # (lo, hi, hash)
bounds = entries + [2048]
for i, e in enumerate(entries):
    progs.append((e, bounds[i + 1], code_hash(e)))
w = out.write
w("/* hle_vu1_aot.h - generated by tools/vu1_aot.py from the game's VU1 code: keep private */\n")
w("static const struct { uint32_t lo, hi, hash; } aot_prog[%d] = {%s};\n" % (len(progs), ", ".join("{0x%03x, 0x%03x, 0x%08xu}" % p for p in progs)))
w("static uint64_t aot_mpg = ~0ull; static int aot_ok[%d];\n" % len(progs))
w("static uint64_t st_aot_runs, st_aot_back;\n")
w("static uint32_t aot_run(uint32_t pc, VStep *s)\n{\n")
w("    if (aot_mpg != st_mpg) { aot_mpg = st_mpg; for (int i = 0; i < %d; i++) aot_ok[i] = code_hash(aot_prog[i].lo) == aot_prog[i].hash; }\n" % len(progs))
w("    for (int i = 0; i < %d; i++) if (pc >= aot_prog[i].lo && pc < aot_prog[i].hi && !aot_ok[i]) return VU_NOAOT;\n" % len(progs))
w("    st_aot_runs++;\n    for (;;) {\n        switch (pc) {\n")
for pc in pcs:
    pi = max(i for i, p in enumerate(progs) if p[0] <= pc)
    w("        case 0x%03x: pc = vu_step(0x%03x, 0x%08xu, 0x%08xu, s); break;\n" % (pc, pc, word(pc, 0), word(pc, 1)))
w("        default: st_aot_back++; return pc;\n        }\n")
w("        if (pc == VU_END) return VU_END;\n")
# leaving a program's range while the other is not verified: back to the interpreter
w("        for (int i = 0; i < %d; i++) if (pc >= aot_prog[i].lo && pc < aot_prog[i].hi && !aot_ok[i]) return pc;\n" % len(progs))
w("    }\n}\n")
out.close()
print("programs", [(hex(a), hex(b), hex(h)) for a, b, h in progs], "instructions", len(pcs))
